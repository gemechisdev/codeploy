#!/usr/bin/env python3
"""Generate internal/api/stubs_gen.go: every route owned by P2+ with its x-permission from api/openapi.yaml.
Requires PyYAML. Routes implemented in P1 are listed in CORE and skipped."""
import re, yaml
d = yaml.safe_load(open('api/openapi.yaml'))
CORE = {'/setup/state','/setup/admin','/setup/resume','/setup/totp/enroll','/setup/totp/verify','/setup/verify-domain','/setup/panel-domain','/setup/operator-candidates','/setup/operator','/setup/complete','/auth/login','/auth/totp/verify','/auth/me','/auth/step-up','/auth/logout','/users','/users/{id}','/tokens','/tokens/{id}','/roles','/permissions','/audit','/audit/verify','/system/status','/system/version','/modules','/modules/{key}','/feature-flags','/settings','/events'}
def mod(p):
    for pre, m in [('/hardening','hardening'),('/edge','edge'),('/domains','edge'),('/terminal','terminal'),('/git','git'),('/webhooks','git'),('/hooks','git'),('/notifications','notify'),('/alerts','notify'),('/backups','databases'),('/templates','templates')]:
        if p.startswith(pre): return m
    if re.search(r'/backups', p): return 'databases'
    if re.search(r'/(source|deploy-key|deploy-hook|webhook)', p): return 'git'
    if re.search(r'/domains', p): return 'edge'
    if p == '/system/metrics': return 'monitor'
    return 'deploy'
out = ['// Code generated by scripts/gen_stubs.py from api/openapi.yaml; DO NOT EDIT.\n', 'package api\n\n',
       '// laterPhase lists every route owned by phases P2+. They declare their permission now so the authz matrix covers them.\n', 'var laterPhase = []RouteDef{\n']
for p, ops in d['paths'].items():
    if p in CORE: continue
    for m, o in ops.items():
        if m not in ('get','post','put','patch','delete'): continue
        perm = o.get('x-permission'); assert perm, (m, p)
        out.append('\t{Method: "%s", Path: "%s", Perm: "%s", Module: "%s"},\n' % (m.upper(), p, perm, mod(p)))
out.append('}\n')
# newline="\n" keeps generated Go platform-independent: text-mode writes on Windows would CRLF the file and break gofmt and the CI drift check.
open('internal/api/stubs_gen.go', 'w', newline='\n').write(''.join(out))
